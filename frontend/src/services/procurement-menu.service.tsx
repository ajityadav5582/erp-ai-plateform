import { api } from "./api";

/**
 * Procurement menu item as returned by the backend.
 */
export interface ProcurementMenuItem {
  title: string;
  href: string;
  icon: string;
  permission: string;
  description: string;
}

/**
 * Full procurement menu response.
 */
export interface ProcurementMenuResponse {
  items: ProcurementMenuItem[];
}

const PROCUREMENT_MENU_URL = "/procurement/menu";

/**
 * Procurement menu API endpoints with RTK Query caching.
 */
export const procurementMenuApi = api.injectEndpoints({
  endpoints: (build) => ({
    /**
     * Fetches the procurement menu configuration for the current user.
     * The backend filters items based on the user's permissions.
     */
    getProcurementMenu: build.query<ProcurementMenuResponse, void>({
      query: () => ({
        url: PROCUREMENT_MENU_URL,
        method: "GET",
      }),
      providesTags: ["ProcurementMenu"],
    }),
  }),
});

export const { useGetProcurementMenuQuery } = procurementMenuApi;

