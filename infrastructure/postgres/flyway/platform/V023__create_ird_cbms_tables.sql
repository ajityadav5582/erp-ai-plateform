-- Persistence required by the existing company IRD configuration and CBMS outbox entities.
CREATE TABLE IF NOT EXISTS company_ird_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    seller_pan VARCHAR(9) NOT NULL,
    api_username VARCHAR(128) NOT NULL,
    api_password_encrypted VARCHAR(512) NOT NULL,
    environment VARCHAR(16) NOT NULL,
    is_cbms_active BOOLEAN NOT NULL DEFAULT FALSE,
    verification_status VARCHAR(32) NOT NULL,
    last_verified_at TIMESTAMPTZ,
    last_error_message VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_company_ird_config_tenant_company UNIQUE (tenant_id, company_id)
);

CREATE TABLE IF NOT EXISTS ird_sync_outbox (
    id UUID PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    source_module VARCHAR(16) NOT NULL,
    source_transaction_id BIGINT NOT NULL,
    invoice_number VARCHAR(100) NOT NULL,
    invoice_type VARCHAR(32) NOT NULL,
    payload_json TEXT NOT NULL,
    sync_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    retry_count INTEGER NOT NULL DEFAULT 0,
    max_retries INTEGER NOT NULL DEFAULT 5,
    next_retry_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_attempted_at TIMESTAMPTZ,
    last_response_code INTEGER,
    last_error_message TEXT,
    version INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ird_outbox_poll
    ON ird_sync_outbox (sync_status, next_retry_at);
CREATE INDEX IF NOT EXISTS idx_ird_outbox_source
    ON ird_sync_outbox (tenant_id, company_id, source_transaction_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ird_outbox_source_document
    ON ird_sync_outbox (tenant_id, company_id, source_module, source_transaction_id, invoice_type);
