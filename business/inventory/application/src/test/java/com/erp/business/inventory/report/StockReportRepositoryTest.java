/**
 * Proves the stock report native queries actually run against real PostgreSQL and
 * that the warehouse filter narrows the result set.
 *
 * <p>This is the check a compile or type-check cannot make: the report queries are
 * native SQL using PostgreSQL-only features ({@code GREATEST}, {@code EXTRACT(EPOCH …)},
 * {@code COUNT(*) FILTER (WHERE …)}, {@code NULLS FIRST}) and the schema is generated by
 * Hibernate {@code ddl-auto}, so only a real engine can confirm they execute and filter.
 * An embedded H2 would reject that SQL, hence Testcontainers.
 */
@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Testcontainers
class StockReportRepositoryTest {

    private static final Long TENANT = 1L;
    private static final Long COMPANY = 1L;

    @Container
    static PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16-alpine");

    @DynamicPropertySource
    static void datasourceProperties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", postgres::getJdbcUrl);
        registry.add("spring.datasource.username", postgres::getUsername);
        registry.add("spring.datasource.password", postgres::getPassword);
        // Fresh schema per run from the entities; the app itself uses ddl-auto=update.
        registry.add("spring.jpa.hibernate.ddl-auto", () -> "create");
    }

    @Autowired private StockBalanceRepository balanceRepository;
    @Autowired private ItemRepository itemRepository;
    @Autowired private WarehouseRepository warehouseRepository;
    @Autowired private UnitRepository unitRepository;
    @Autowired private EntityManager entityManager;

    @SuppressWarnings("removal")
    @MockBean private PlatformJwtAuthenticationFilter platformJwtAuthenticationFilter;

    @SuppressWarnings("removal")
    @MockBean private KafkaTemplate<String, Object> kafkaTemplate;

    private Long warehouseA;
    private Long warehouseB;

    @BeforeEach
    void seed() {
        Unit unit = unitRepository.save(
                Unit.create(TENANT, COMPANY, "Piece", "PCS", UnitDimension.COUNT, "pc", 0));

        Warehouse a = warehouseRepository.save(
                Warehouse.create(TENANT, COMPANY, "WH-A", "Warehouse A",
                        WarehouseType.GENERAL, null, null, null));
        Warehouse b = warehouseRepository.save(
                Warehouse.create(TENANT, COMPANY, "WH-B", "Warehouse B",
                        WarehouseType.GENERAL, null, null, null));
        warehouseA = a.getId();
        warehouseB = b.getId();

        Item item = Item.builder()
                .sku("SKU-001")
                .nameEn("Widget")
                .uom(unit)
                .sellingPrice(new BigDecimal("100.00"))
                .purchasePrice(new BigDecimal("40.00"))
                .build();
        item.assignScope(TENANT, COMPANY);
        Item savedItem = itemRepository.save(item);

        balanceRepository.save(balance(savedItem.getId(), unit.getId(), warehouseA, "10"));
        balanceRepository.save(balance(savedItem.getId(), unit.getId(), warehouseB, "5"));

        // Native queries bypass the persistence context, so the seeded rows must reach
        // the database before the report queries run.
        entityManager.flush();
    }

    private static StockBalance balance(Long itemId, Long unitId, Long warehouseId, String onHand) {
        StockBalance b = StockBalance.builder()
                .warehouseId(warehouseId)
                .itemId(itemId)
                .unitId(unitId)
                .onHandQty(new BigDecimal(onHand).setScale(6))
                .reservedQty(BigDecimal.ZERO.setScale(6))
                .build();
        b.assignScope(TENANT, COMPANY);
        return b;
    }

    @Test
    void onHand_withoutWarehouseFilter_returnsEveryBalance() {
        Page<StockOnHandProjection> page = balanceRepository.findOnHand(
                TENANT, COMPANY, null, null, false, PageRequest.of(0, 20));

        assertThat(page.getContent()).hasSize(2);
        assertThat(page.getTotalElements()).isEqualTo(2);
        assertThat(page.getContent())
                .extracting(StockOnHandProjection::getWarehouseId)
                .containsExactlyInAnyOrder(warehouseA, warehouseB);
    }

    @Test
    void onHand_withWarehouseFilter_returnsOnlyThatWarehouse() {
        Page<StockOnHandProjection> page = balanceRepository.findOnHand(
                TENANT, COMPANY, warehouseA, null, false, PageRequest.of(0, 20));

        assertThat(page.getContent()).hasSize(1);
        StockOnHandProjection row = page.getContent().get(0);
        assertThat(row.getWarehouseId()).isEqualTo(warehouseA);
        assertThat(row.getSku()).isEqualTo("SKU-001");
        assertThat(row.getWarehouseCode()).isEqualTo("WH-A");
        // available = on_hand - reserved = 10 - 0
        assertThat(row.getAvailable()).isEqualByComparingTo("10");
    }

    @Test
    void onHand_withUnknownWarehouseFilter_returnsNothing() {
        Page<StockOnHandProjection> page = balanceRepository.findOnHand(
                TENANT, COMPANY, 9999L, null, false, PageRequest.of(0, 20));

        assertThat(page.getContent()).isEmpty();
        assertThat(page.getTotalElements()).isZero();
    }
}
