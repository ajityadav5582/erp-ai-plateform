    CONSTRAINT uk_actions_action_code UNIQUE (action_code),
    CONSTRAINT chk_actions_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT chk_actions_action_code_length CHECK (length(action_code) <= 50),
    CONSTRAINT chk_actions_action_name_length CHECK (length(action_name) <= 100),
    CONSTRAINT chk_actions_description_length CHECK (description IS NULL OR length(description) <= 500)
);

