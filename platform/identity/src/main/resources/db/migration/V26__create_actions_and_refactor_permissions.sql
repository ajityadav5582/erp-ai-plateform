-- ============================================================
-- 4. Refactor permissions table
-- ============================================================

-- Add new columns for database-backed resource and action references
ALTER TABLE permissions
    ADD COLUMN IF NOT EXISTS resource_id BIGINT,
    ADD COLUMN IF NOT EXISTS action_id BIGINT,
    ADD COLUMN IF NOT EXISTS permission_name VARCHAR(200),
    ADD COLUMN IF NOT EXISTS is_system BOOLEAN NOT NULL DEFAULT false;

-- Add foreign key constraints idempotently so an interrupted or manually
-- replayed migration can be retried safely.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conrelid = 'permissions'::regclass
           AND conname = 'fk_permissions_resource_id'
    ) THEN
        ALTER TABLE permissions
            ADD CONSTRAINT fk_permissions_resource_id
            FOREIGN KEY (resource_id) REFERENCES resources(id)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conrelid = 'permissions'::regclass
           AND conname = 'fk_permissions_action_id'
    ) THEN
        ALTER TABLE permissions
            ADD CONSTRAINT fk_permissions_action_id
            FOREIGN KEY (action_id) REFERENCES actions(id)
            ON DELETE RESTRICT;
    END IF;
END $$;

-- Migrate existing data: map enum resource/action values to resource/action IDs.
-- Skip this step when a previous attempt already dropped the legacy columns.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM pg_attribute
         WHERE attrelid = 'permissions'::regclass
           AND attname = 'resource'
           AND attnum > 0
           AND NOT attisdropped
    ) AND EXISTS (
        SELECT 1
          FROM pg_attribute
         WHERE attrelid = 'permissions'::regclass
           AND attname = 'action'
           AND attnum > 0
           AND NOT attisdropped
    ) THEN
        UPDATE permissions p
           SET resource_id = r.id,
               action_id = a.id
          FROM resources r, actions a
         WHERE p.resource = r.resource_code
           AND p.action = a.action_code;
    END IF;
END $$;

